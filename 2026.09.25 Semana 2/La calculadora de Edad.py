# Crea una variable con el año actual
anio_actual = 2026

# Pide al usuario su edad actual (convertido a entero)
edad = int(input("¿Cuántos años tiene? "))

# Realiza la resta para hallar el año de nacimiento
anio_nacimiento = anio_actual - edad

# Muestra el resultado final
print("Usted nació aproximadamente en:", anio_nacimiento)